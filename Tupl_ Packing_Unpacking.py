# Q3 - Tuple Packing and Unpacking

# a. Pack book information into a tuple
book_info = ("The Alchemist", "Paulo Coelho", 1988)
print("Packed tuple:", book_info)

# b. Unpack into separate variables
title, author, year = book_info

# Print in readable format
print(f"Title: {title}")
print(f"Author: {author}")
print(f"Publication Year: {year}")